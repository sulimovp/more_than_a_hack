"""One-at-a-time sensitivity of the pipeline's constants.

    python analysis/sensitivity.py            # writes analysis/sensitivity.md

This is a robustness check, not a tuner: the defaults should sit on a plateau where halving or
doubling a constant moves nothing much. A constant whose move swings the public score is a
constant to fix with the hand-labelled windows (PLAN.md 5.2), never with the public window, whose
17 possessions put the noise band at about +/-0.15 spellF1.
"""

import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
from possession import control, decoder, io, liveness, pipeline, report  # noqa: E402

import possession_metrics as pm  # noqa: E402

# (module, name, values); the first value of each list is the default
SWEEP = [
    (decoder, "SWITCH", [-6.0, -3.0, -12.0]),
    (decoder, "LIVE_TO_DEAD", [-15.0, -8.0, -25.0]),
    (decoder, "DEAD_TO_LIVE", [-15.0, -8.0, -25.0]),
    (decoder, "MIN_LIVE", [8, 4, 16]),
    (decoder, "MIN_DEAD", [50, 25, 100]),
    (control, "EVIDENCE_GAIN", [3.0, 1.5, 6.0]),
    (control, "CONTACT_SCALE_M", [1.0, 0.7, 1.5]),
    (liveness, "SPEED_PIVOT", [1.25, 1.1, 1.4]),
    (liveness, "GAP_PIVOT", [1.4, 1.25, 1.6]),
    (liveness, "WHISTLE_BONUS", [4.0, 0.0, 8.0]),
    (liveness, "ACTIVITY_GAIN", [0.5, 0.0, 1.0]),
]


def summary(codes, tags):
    gt = io.load_gt_public()
    res = pm.evaluate(gt, codes, bootstrap_n=0)
    lines = []
    report.weak_checks(codes, tags, out=lines.append)
    graded = io.graded_mask()
    runs = [(first, stop) for _, first, stop in io.halves()]
    spells = [s for s in pm.segments(codes, runs) if s[2] < 2]
    agree = float(lines[-1].split(":")[1].split("%")[0])
    setp = lines[-2].rsplit(":", 1)[1].strip()
    return (res["spell_f1_mean"], res["macro_f1"], len(spells),
            float(np.mean(codes[graded] == io.DEAD)), setp, agree)


def run_once():
    # features() reads the module constants, so rebuild it each time (about 10 s)
    f = pipeline.features()
    first = pipeline.decode(f, switch=decoder.SWITCH, live_to_dead=decoder.LIVE_TO_DEAD,
                            dead_to_live=decoder.DEAD_TO_LIVE, min_live=decoder.MIN_LIVE,
                            min_dead=decoder.MIN_DEAD)
    team = pipeline.add_shape(f, first)
    codes = pipeline.decode(f, team, switch=decoder.SWITCH, live_to_dead=decoder.LIVE_TO_DEAD,
                            dead_to_live=decoder.DEAD_TO_LIVE, min_live=decoder.MIN_LIVE,
                            min_dead=decoder.MIN_DEAD)
    return summary(codes, f["tags"])


def main():
    rows = ["| constant | value | public spellF1 | public macroF1 | possessions (full) | D share | set pieces | phase agreement |",
            "|---|---|---|---|---|---|---|---|"]
    base = run_once()
    rows.append("| defaults | | {:.3f} | {:.3f} | {} | {:.1%} | {} | {:.1f}% |".format(*base))
    for module, name, values in SWEEP:
        default = getattr(module, name)
        for value in values[1:]:
            setattr(module, name, value)
            r = run_once()
            rows.append("| {} | {} | {:.3f} | {:.3f} | {} | {:.1%} | {} | {:.1f}% |".format(name, value, *r))
            print(rows[-1], flush=True)
        setattr(module, name, default)
    with open(os.path.join(HERE, "sensitivity.md"), "w") as handle:
        handle.write("# One-at-a-time sensitivity\n\nGenerated by `python analysis/sensitivity.py`. "
                     "Public numbers are 17 possessions: about +/-0.15 spellF1 is noise.\n\n")
        handle.write("\n".join(rows) + "\n")


if __name__ == "__main__":
    main()
