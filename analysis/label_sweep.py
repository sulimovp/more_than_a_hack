"""Score pipeline variants on the hand-labelled transitions (validation only; no label enters the file).

    python -m analysis.label_sweep            # writes analysis/label_sweep.md

The labels say, for each transition the submitted file predicts, whether it is real (y, or e with the
real frame) or invented (n). A variant can only be judged on those transitions, so it is scored on
what it does to them: how many real ones it keeps (a transition of the same kind within 1 s of the real
frame) and how many invented ones it removes (no transition of that kind within 1 s of the predicted
frame). Answers t (a different change) and s (skip) are left out. New transitions a variant adds are
not labelled; the full-match possession count and the weak checks watch for them, and the public
window must keep every possession it matches.
"""

import glob
import os

import numpy as np

from analysis.sensitivity import summary
from possession import control, decoder, io, liveness, pipeline
from tools.transition_review import load_answers

LABEL_DIR = os.path.join(io.DATA_DIR, "labels")
LETTER = {io.HOME: "H", io.AWAY: "A", io.DEAD: "D"}
TOL = io.FPS

# (label, module constants to set, decoder keyword overrides)
VARIANTS = [
    ("submitted", {}, {}),
    ("SWITCH -9", {}, {"switch": -9.0}),
    ("SWITCH -12", {}, {"switch": -12.0}),
    ("SWITCH -18", {}, {"switch": -18.0}),
    ("live/dead -25", {}, {"live_to_dead": -25.0, "dead_to_live": -25.0}),
    ("live/dead -40", {}, {"live_to_dead": -40.0, "dead_to_live": -40.0}),
    ("SWITCH -12, live/dead -25", {}, {"switch": -12.0, "live_to_dead": -25.0, "dead_to_live": -25.0}),
    ("EVIDENCE_GAIN 1.5", {(control, "EVIDENCE_GAIN"): 1.5}, {}),
    ("CONTACT_SCALE_M 0.7", {(control, "CONTACT_SCALE_M"): 0.7}, {}),
    ("SPEED_PIVOT 1.4", {(liveness, "SPEED_PIVOT"): 1.4}, {}),
]


def labelled():
    """[(frame, transition, answer, real_frame)] over every answer file, skips and disagreements dropped."""
    votes = {}
    for path in glob.glob(os.path.join(LABEL_DIR, "transitions_*.csv")):
        for key, (ans, tf) in load_answers(path).items():
            if ans in "YENT":
                votes.setdefault(key, []).append((ans, tf))
    out = []
    for (frame, trans), vs in votes.items():
        if len({v[0] for v in vs}) == 1:
            ans, tf = vs[0]
            out.append((frame, trans, ans, tf if tf is not None else frame))
    return out


def transitions(codes):
    idx = np.flatnonzero(codes[1:] != codes[:-1]) + 1
    graded = io.graded_mask()
    return [(int(f), LETTER.get(int(codes[f - 1]), "X") + ">" + LETTER.get(int(codes[f]), "X"))
            for f in idx if graded[f] and graded[f - 1]]


def label_score(codes, labels):
    have = {}
    for f, t in transitions(codes):
        have.setdefault(t, []).append(f)
    near = lambda t, f: any(abs(g - f) <= TOL for g in have.get(t, []))
    real = [(f, t, rf) for f, t, a, rf in labels if a in "YE"]
    fake = [(f, t) for f, t, a, _ in labels if a == "N"]
    kept = sum(near(t, rf) for f, t, rf in real)
    removed = sum(not near(t, f) for f, t in fake)
    return kept, len(real), removed, len(fake)


def run_variant(constants, params):
    saved = {k: getattr(*k) for k in constants}
    for (module, name), value in constants.items():
        setattr(module, name, value)
    try:
        f = pipeline.features()
        kw = dict(switch=decoder.SWITCH, live_to_dead=decoder.LIVE_TO_DEAD, dead_to_live=decoder.DEAD_TO_LIVE,
                  min_live=decoder.MIN_LIVE, min_dead=decoder.MIN_DEAD)
        kw.update(params)
        first = pipeline.decode(f, **kw)
        codes = pipeline.decode(f, pipeline.add_shape(f, first), **kw)
        return codes, f["tags"]
    finally:
        for (module, name), value in saved.items():
            setattr(module, name, value)


def main():
    labels = labelled()
    print("{} labelled transitions".format(len(labels)), flush=True)
    rows = ["| variant | real kept | invented removed | public spellF1 | public macroF1 | possessions | D share | set pieces | phase |",
            "|---|---|---|---|---|---|---|---|---|"]
    for name, constants, params in VARIANTS:
        codes, tags = run_variant(constants, params)
        k, nk, r, nr = label_score(codes, labels)
        s = summary(codes, tags)
        rows.append("| {} | {}/{} ({:.0%}) | {}/{} ({:.0%}) | {:.3f} | {:.3f} | {} | {:.1%} | {} | {:.1f}% |".format(
            name, k, nk, k / nk, r, nr, r / nr, *s))
        print(rows[-1], flush=True)
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "label_sweep.md"), "w") as handle:
        handle.write("# Variants scored on the hand-labelled transitions\n\nGenerated by `python -m analysis.label_sweep` "
                     "on {} labelled transitions. Validation only.\n\n".format(len(labels)))
        handle.write("\n".join(rows) + "\n")


if __name__ == "__main__":
    main()
